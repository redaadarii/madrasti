-- Menu de la cantine : un menu par jour d'ouverture
CREATE TABLE canteen_menus (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_date   DATE         NOT NULL,
    starter     VARCHAR(150),
    main_course VARCHAR(150) NOT NULL,
    side        VARCHAR(150),
    dessert     VARCHAR(150),
    vegetarian  VARCHAR(150),
    allergens   VARCHAR(200),
    created_at  TIMESTAMP    NOT NULL,
    updated_at  TIMESTAMP    NOT NULL,
    CONSTRAINT uk_canteen_menus_date UNIQUE (menu_date)
);
