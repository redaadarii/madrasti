-- Langue préférée (notifications, SMS) et code Massar (export ministériel)
ALTER TABLE users ADD COLUMN language VARCHAR(2) NOT NULL DEFAULT 'fr';
ALTER TABLE students ADD COLUMN massar_code VARCHAR(20);

-- Notifications in-app (texte construit côté client à partir du type et des paramètres)
CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type       VARCHAR(30)  NOT NULL,
    link       VARCHAR(200),
    read_at    TIMESTAMP,
    created_at TIMESTAMP    NOT NULL,
    updated_at TIMESTAMP    NOT NULL
);
CREATE INDEX idx_notifications_user ON notifications (user_id, created_at);

CREATE TABLE notification_params (
    notification_id BIGINT       NOT NULL REFERENCES notifications (id) ON DELETE CASCADE,
    param_name      VARCHAR(40)  NOT NULL,
    param_value     VARCHAR(255) NOT NULL,
    PRIMARY KEY (notification_id, param_name)
);

-- Journal des SMS envoyés
CREATE TABLE sms_messages (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    to_phone       VARCHAR(30),
    recipient_name VARCHAR(160) NOT NULL,
    body           VARCHAR(640) NOT NULL,
    status         VARCHAR(10)  NOT NULL,
    error          VARCHAR(255),
    sent_by        BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at     TIMESTAMP    NOT NULL,
    updated_at     TIMESTAMP    NOT NULL
);

-- Dépenses : bon de commande → facture → paiement
CREATE TABLE expenses (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label      VARCHAR(150)   NOT NULL,
    category   VARCHAR(20)    NOT NULL,
    supplier   VARCHAR(150),
    reference  VARCHAR(40),
    amount     NUMERIC(12, 2) NOT NULL,
    status     VARCHAR(10)    NOT NULL,
    ordered_on DATE           NOT NULL,
    paid_on    DATE,
    created_at TIMESTAMP      NOT NULL,
    updated_at TIMESTAMP      NOT NULL
);

-- Fichiers déposés (photos, supports de cours) : identifiant non devinable
CREATE TABLE stored_files (
    id            VARCHAR(36)  PRIMARY KEY,
    original_name VARCHAR(255) NOT NULL,
    content_type  VARCHAR(100) NOT NULL,
    size_bytes    BIGINT       NOT NULL,
    uploaded_by   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at    TIMESTAMP    NOT NULL
);

-- Galerie photo
CREATE TABLE albums (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(150) NOT NULL,
    description  VARCHAR(500),
    classroom_id BIGINT REFERENCES classrooms (id) ON DELETE CASCADE,
    author_id    BIGINT       NOT NULL REFERENCES users (id),
    created_at   TIMESTAMP    NOT NULL,
    updated_at   TIMESTAMP    NOT NULL
);

CREATE TABLE photos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    album_id   BIGINT       NOT NULL REFERENCES albums (id) ON DELETE CASCADE,
    file_id    VARCHAR(36)  NOT NULL REFERENCES stored_files (id),
    caption    VARCHAR(200),
    created_at TIMESTAMP    NOT NULL,
    updated_at TIMESTAMP    NOT NULL
);

-- Cours en ligne : supports (fichier) ou liens (vidéo, site)
CREATE TABLE course_resources (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id BIGINT       NOT NULL REFERENCES classrooms (id) ON DELETE CASCADE,
    teacher_id   BIGINT       NOT NULL REFERENCES users (id),
    subject      VARCHAR(80)  NOT NULL,
    title        VARCHAR(150) NOT NULL,
    description  VARCHAR(500),
    kind         VARCHAR(10)  NOT NULL,
    url          VARCHAR(500),
    file_id      VARCHAR(36) REFERENCES stored_files (id),
    created_at   TIMESTAMP    NOT NULL,
    updated_at   TIMESTAMP    NOT NULL
);

-- Conseil de classe : décision et appréciation par élève et par trimestre
CREATE TABLE council_decisions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id   BIGINT       NOT NULL REFERENCES students (id) ON DELETE CASCADE,
    term         VARCHAR(20)  NOT NULL,
    decision     VARCHAR(20)  NOT NULL,
    appreciation VARCHAR(500),
    created_at   TIMESTAMP    NOT NULL,
    updated_at   TIMESTAMP    NOT NULL,
    CONSTRAINT uk_council UNIQUE (student_id, term)
);
