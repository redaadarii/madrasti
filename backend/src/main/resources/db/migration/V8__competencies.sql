-- Bulletins par compétences : référentiel par matière et évaluations par trimestre
CREATE TABLE competencies (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject    VARCHAR(60)  NOT NULL,
    label      VARCHAR(200) NOT NULL,
    level      VARCHAR(40),
    created_at TIMESTAMP    NOT NULL,
    updated_at TIMESTAMP    NOT NULL
);

CREATE TABLE competency_assessments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id    BIGINT      NOT NULL REFERENCES students (id) ON DELETE CASCADE,
    competency_id BIGINT      NOT NULL REFERENCES competencies (id) ON DELETE CASCADE,
    term          VARCHAR(5)  NOT NULL,
    mastery       VARCHAR(15) NOT NULL,
    assessed_by   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at    TIMESTAMP   NOT NULL,
    updated_at    TIMESTAMP   NOT NULL,
    CONSTRAINT uk_competency_assessment UNIQUE (student_id, competency_id, term)
);
CREATE INDEX idx_competency_assessments_student ON competency_assessments (student_id, term);
