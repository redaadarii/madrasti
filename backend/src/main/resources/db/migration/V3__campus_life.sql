-- Emploi du temps
CREATE TABLE timetable_slots (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id BIGINT      NOT NULL REFERENCES classrooms (id) ON DELETE CASCADE,
    teacher_id   BIGINT REFERENCES users (id),
    day_of_week  INT         NOT NULL,
    start_time   TIME        NOT NULL,
    end_time     TIME        NOT NULL,
    subject      VARCHAR(80) NOT NULL,
    room         VARCHAR(40),
    created_at   TIMESTAMP   NOT NULL,
    updated_at   TIMESTAMP   NOT NULL
);
CREATE INDEX idx_slots_classroom ON timetable_slots (classroom_id);

-- Agenda : événements, contrôles, vacances, réunions
CREATE TABLE events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(150) NOT NULL,
    description  TEXT,
    kind         VARCHAR(20)  NOT NULL,
    starts_at    TIMESTAMP    NOT NULL,
    ends_at      TIMESTAMP,
    classroom_id BIGINT REFERENCES classrooms (id) ON DELETE CASCADE,
    author_id    BIGINT       NOT NULL REFERENCES users (id),
    created_at   TIMESTAMP    NOT NULL,
    updated_at   TIMESTAMP    NOT NULL
);
CREATE INDEX idx_events_starts ON events (starts_at);

-- Messagerie
CREATE TABLE conversations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject         VARCHAR(150) NOT NULL,
    last_message_at      TIMESTAMP    NOT NULL,
    last_message_preview VARCHAR(200) NOT NULL,
    created_at      TIMESTAMP    NOT NULL,
    updated_at      TIMESTAMP    NOT NULL
);

CREATE TABLE conversation_participants (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT    NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    user_id         BIGINT    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    last_read_at    TIMESTAMP,
    created_at      TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP NOT NULL,
    CONSTRAINT uk_participant UNIQUE (conversation_id, user_id)
);
CREATE INDEX idx_participants_user ON conversation_participants (user_id);

CREATE TABLE messages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT    NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    sender_id       BIGINT    NOT NULL REFERENCES users (id),
    body            TEXT      NOT NULL,
    created_at      TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP NOT NULL
);
CREATE INDEX idx_messages_conversation ON messages (conversation_id);

-- Réclamations
CREATE TABLE complaints (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id   BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    student_id  BIGINT REFERENCES students (id) ON DELETE SET NULL,
    category    VARCHAR(20)  NOT NULL,
    subject     VARCHAR(150) NOT NULL,
    body        TEXT         NOT NULL,
    status      VARCHAR(20)  NOT NULL,
    response    TEXT,
    created_at  TIMESTAMP    NOT NULL,
    updated_at  TIMESTAMP    NOT NULL
);

-- Quiz en ligne (QCM auto-corrigés)
CREATE TABLE quizzes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id BIGINT       NOT NULL REFERENCES classrooms (id) ON DELETE CASCADE,
    teacher_id   BIGINT       NOT NULL REFERENCES users (id),
    subject      VARCHAR(80)  NOT NULL,
    title        VARCHAR(150) NOT NULL,
    due_date     DATE         NOT NULL,
    created_at   TIMESTAMP    NOT NULL,
    updated_at   TIMESTAMP    NOT NULL
);

CREATE TABLE quiz_questions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id       BIGINT       NOT NULL REFERENCES quizzes (id) ON DELETE CASCADE,
    position      INT          NOT NULL,
    prompt        VARCHAR(500) NOT NULL,
    correct_index INT          NOT NULL
);

CREATE TABLE quiz_choices (
    question_id BIGINT       NOT NULL REFERENCES quiz_questions (id) ON DELETE CASCADE,
    position    INT          NOT NULL,
    label       VARCHAR(255) NOT NULL,
    PRIMARY KEY (question_id, position)
);

CREATE TABLE quiz_attempts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id      BIGINT       NOT NULL REFERENCES quizzes (id) ON DELETE CASCADE,
    student_id   BIGINT       NOT NULL REFERENCES students (id) ON DELETE CASCADE,
    answers      VARCHAR(500) NOT NULL,
    score        INT          NOT NULL,
    total        INT          NOT NULL,
    submitted_at TIMESTAMP    NOT NULL,
    created_at   TIMESTAMP    NOT NULL,
    updated_at   TIMESTAMP    NOT NULL,
    CONSTRAINT uk_attempt UNIQUE (quiz_id, student_id)
);

-- Services : transport, cantine, activités
CREATE TABLE school_services (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        VARCHAR(20)    NOT NULL,
    name        VARCHAR(120)   NOT NULL,
    description VARCHAR(500),
    schedule    VARCHAR(120),
    monthly_fee NUMERIC(10, 2) NOT NULL,
    capacity    INT,
    active      BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP      NOT NULL,
    updated_at  TIMESTAMP      NOT NULL
);

CREATE TABLE service_subscriptions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id  BIGINT    NOT NULL REFERENCES school_services (id) ON DELETE CASCADE,
    student_id  BIGINT    NOT NULL REFERENCES students (id) ON DELETE CASCADE,
    created_at  TIMESTAMP NOT NULL,
    updated_at  TIMESTAMP NOT NULL,
    CONSTRAINT uk_subscription UNIQUE (service_id, student_id)
);

-- Bibliothèque
CREATE TABLE books (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(200) NOT NULL,
    author     VARCHAR(150) NOT NULL,
    isbn       VARCHAR(20),
    category   VARCHAR(60)  NOT NULL,
    copies     INT          NOT NULL,
    created_at TIMESTAMP    NOT NULL,
    updated_at TIMESTAMP    NOT NULL
);

CREATE TABLE loans (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id     BIGINT    NOT NULL REFERENCES books (id) ON DELETE CASCADE,
    student_id  BIGINT    NOT NULL REFERENCES students (id) ON DELETE CASCADE,
    borrowed_on DATE      NOT NULL,
    due_on      DATE      NOT NULL,
    returned_on DATE,
    created_at  TIMESTAMP NOT NULL,
    updated_at  TIMESTAMP NOT NULL
);
CREATE INDEX idx_loans_book ON loans (book_id);

-- Pré-inscriptions en ligne (formulaire public)
CREATE TABLE pre_registrations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    child_first_name VARCHAR(80)  NOT NULL,
    child_last_name  VARCHAR(80)  NOT NULL,
    birth_date       DATE         NOT NULL,
    desired_level    VARCHAR(60)  NOT NULL,
    parent_name      VARCHAR(150) NOT NULL,
    parent_email     VARCHAR(150) NOT NULL,
    parent_phone     VARCHAR(30)  NOT NULL,
    message          VARCHAR(1000),
    status           VARCHAR(20)  NOT NULL,
    created_at       TIMESTAMP    NOT NULL,
    updated_at       TIMESTAMP    NOT NULL
);
