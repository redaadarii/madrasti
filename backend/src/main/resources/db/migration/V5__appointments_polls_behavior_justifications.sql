-- Rendez-vous parents-professeurs : créneaux publiés par l'enseignant, réservés par un parent
CREATE TABLE appointment_slots (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id       BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    starts_at        TIMESTAMP    NOT NULL,
    duration_minutes INT          NOT NULL,
    mode             VARCHAR(10)  NOT NULL,
    location         VARCHAR(150),
    parent_id        BIGINT REFERENCES users (id) ON DELETE SET NULL,
    student_id       BIGINT REFERENCES students (id) ON DELETE CASCADE,
    topic            VARCHAR(300),
    created_at       TIMESTAMP    NOT NULL,
    updated_at       TIMESTAMP    NOT NULL
);
CREATE INDEX idx_appointment_slots_teacher ON appointment_slots (teacher_id, starts_at);

-- Sondages : une seule réponse par utilisateur
CREATE TABLE polls (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question   VARCHAR(300) NOT NULL,
    audience   VARCHAR(10)  NOT NULL,
    closes_on  DATE,
    author_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at TIMESTAMP    NOT NULL,
    updated_at TIMESTAMP    NOT NULL
);

CREATE TABLE poll_options (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poll_id  BIGINT       NOT NULL REFERENCES polls (id) ON DELETE CASCADE,
    label    VARCHAR(150) NOT NULL,
    position INT          NOT NULL
);

CREATE TABLE poll_votes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poll_id    BIGINT    NOT NULL REFERENCES polls (id) ON DELETE CASCADE,
    option_id  BIGINT    NOT NULL REFERENCES poll_options (id) ON DELETE CASCADE,
    user_id    BIGINT    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_poll_votes_user UNIQUE (poll_id, user_id)
);

-- Comportement : points positifs et incidents (avec sanction éventuelle)
CREATE TABLE behavior_records (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id  BIGINT      NOT NULL REFERENCES students (id) ON DELETE CASCADE,
    author_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    category    VARCHAR(30) NOT NULL,
    sanction    VARCHAR(20),
    note        VARCHAR(500),
    occurred_on DATE        NOT NULL,
    created_at  TIMESTAMP   NOT NULL,
    updated_at  TIMESTAMP   NOT NULL
);
CREATE INDEX idx_behavior_student ON behavior_records (student_id, occurred_on);

