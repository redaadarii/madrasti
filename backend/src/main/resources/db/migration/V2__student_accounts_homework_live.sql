ALTER TABLE students ADD COLUMN user_id BIGINT UNIQUE REFERENCES users (id);

CREATE TABLE assignments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id BIGINT       NOT NULL REFERENCES classrooms (id) ON DELETE CASCADE,
    teacher_id   BIGINT       NOT NULL REFERENCES users (id),
    subject      VARCHAR(80)  NOT NULL,
    title        VARCHAR(150) NOT NULL,
    description  TEXT         NOT NULL,
    due_date     DATE         NOT NULL,
    created_at   TIMESTAMP    NOT NULL,
    updated_at   TIMESTAMP    NOT NULL
);
CREATE INDEX idx_assignments_classroom ON assignments (classroom_id);

CREATE TABLE submissions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT        NOT NULL REFERENCES assignments (id) ON DELETE CASCADE,
    student_id    BIGINT        NOT NULL REFERENCES students (id) ON DELETE CASCADE,
    content       TEXT          NOT NULL,
    submitted_at  TIMESTAMP     NOT NULL,
    score         NUMERIC(5, 2),
    feedback      VARCHAR(1000),
    created_at    TIMESTAMP     NOT NULL,
    updated_at    TIMESTAMP     NOT NULL,
    CONSTRAINT uk_submission UNIQUE (assignment_id, student_id)
);

CREATE TABLE live_sessions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id     BIGINT       NOT NULL REFERENCES classrooms (id) ON DELETE CASCADE,
    teacher_id       BIGINT       NOT NULL REFERENCES users (id),
    subject          VARCHAR(80)  NOT NULL,
    title            VARCHAR(150) NOT NULL,
    starts_at        TIMESTAMP    NOT NULL,
    duration_minutes INT          NOT NULL,
    provider         VARCHAR(10)  NOT NULL,
    meeting_url      VARCHAR(500) NOT NULL,
    created_at       TIMESTAMP    NOT NULL,
    updated_at       TIMESTAMP    NOT NULL
);
CREATE INDEX idx_live_sessions_classroom ON live_sessions (classroom_id);
